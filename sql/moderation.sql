-- ===========================================================================
-- PHOENIX — Ban Management (moderation) schema
-- ---------------------------------------------------------------------------
-- Run this ONE file in the Supabase SQL Editor, after email-verification.sql.
-- Additive and idempotent: every statement checks first, so re-running is
-- harmless. Nothing here deletes a player's account, badges, statistics or
-- saved progress — revoking a restriction has never needed to.
--
-- Three independent, individually revocable restriction types:
--
--   account  the default, and the only one that is on by default in the UI
--   ip       optional; a network-level restriction, warned about in the UI
--   device   optional; a server-issued token, honestly described as evadable
--
-- A restriction row is ACTIVE when it is not revoked and has not expired:
--
--   revoked_at is null AND (expires_at is null OR expires_at > now())
--
-- expires_at IS NULL means PERMANENT. Permanent rows are ordinary rows — they
-- are revoked exactly the same way temporary ones are, so a permanent ban can
-- always be undone by the owner.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. Restrictions
-- ---------------------------------------------------------------------------
create table if not exists public.moderation_bans (
  id            uuid primary key default gen_random_uuid(),
  kind          text not null,
  account_id    uuid references public.accounts (id) on delete set null,
  account_name  text,                       -- snapshot, so history survives a deletion
  ip            inet,                       -- only for kind = 'ip'
  ip_key        text,                       -- matching key: v4 literal, or v6 /64
  device_id     text,                       -- only for kind = 'device'
  reason        text not null default '',
  duration      integer,                    -- seconds; NULL = permanent
  expires_at    timestamptz,                -- NULL = permanent
  created_at    timestamptz not null default now(),
  created_by    uuid references public.accounts (id) on delete set null,
  created_by_name text,
  revoked_at    timestamptz,
  revoked_by    uuid references public.accounts (id) on delete set null,
  revoked_by_name text,
  constraint moderation_bans_kind check (kind in ('account', 'ip', 'device')),
  constraint moderation_bans_target check (
    (kind = 'account'  and account_id is not null) or
    (kind = 'ip'       and ip is not null) or
    (kind = 'device'   and device_id is not null)
  ),
  constraint moderation_bans_duration check (duration is null or duration > 0)
);

create index if not exists moderation_bans_account on public.moderation_bans (account_id);
create index if not exists moderation_bans_ip      on public.moderation_bans (ip);
create index if not exists moderation_bans_ip_key  on public.moderation_bans (ip_key);
create index if not exists moderation_bans_device  on public.moderation_bans (device_id);
create index if not exists moderation_bans_live
  on public.moderation_bans (created_at desc)
  where revoked_at is null;

alter table public.moderation_bans enable row level security;
revoke all on public.moderation_bans from anon, public;
grant select, insert, update on public.moderation_bans to service_role;

-- ---------------------------------------------------------------------------
-- 2. Devices
-- ---------------------------------------------------------------------------
-- Deliberately NOT a fingerprint. The id below is random bytes generated by
-- the SERVER and handed to the browser in a first-party cookie; nothing about
-- the machine, screen, fonts or clock is measured. Clearing cookies produces
-- a new id, which is a limitation the UI states plainly rather than hides.
-- ---------------------------------------------------------------------------
create table if not exists public.devices (
  device_id     text primary key,
  account_id    uuid references public.accounts (id) on delete set null,
  account_name  text,
  first_seen    timestamptz not null default now(),
  last_seen     timestamptz not null default now(),
  last_ip       inet,
  times_seen    integer not null default 1
);

create index if not exists devices_account on public.devices (account_id);

alter table public.devices enable row level security;
revoke all on public.devices from anon, public;
grant select, insert, update on public.devices to service_role;

-- Which accounts have been seen on which device. This is what lets the owner
-- see "three accounts have used this browser" when deciding about a device
-- restriction — and what stops an IP ban being inferred from a device row.
create table if not exists public.device_accounts (
  device_id   text not null references public.devices (device_id) on delete cascade,
  account_id  uuid not null references public.accounts (id) on delete cascade,
  account_name text,
  first_seen  timestamptz not null default now(),
  last_seen   timestamptz not null default now(),
  primary key (device_id, account_id)
);

alter table public.device_accounts enable row level security;
revoke all on public.device_accounts from anon, public;
grant select, insert, update on public.device_accounts to service_role;

-- ---------------------------------------------------------------------------
-- 3. Audit log (append-only)
-- ---------------------------------------------------------------------------
-- Every moderation decision, actor and outcome. Denied to ordinary users and
-- to the anon key; the owner reads it through the server only.
-- ---------------------------------------------------------------------------
create table if not exists public.moderation_log (
  id          uuid primary key default gen_random_uuid(),
  at          timestamptz not null default now(),
  action      text not null,
  actor_id    uuid,
  actor_name  text,
  subject_id  uuid,
  subject_name text,
  ban_id      uuid,
  detail      text not null default ''
);

create index if not exists moderation_log_recent on public.moderation_log (at desc);

alter table public.moderation_log enable row level security;
revoke all on public.moderation_log from anon, public;
grant select, insert on public.moderation_log to service_role;

-- The log is a record. Nothing may change one after it is written — not even
-- the service role.
create or replace function public.block_moderation_log_mutation()
returns trigger
language plpgsql
as $$
begin
  raise exception 'The moderation audit log is append-only.';
end;
$$;

drop trigger if exists moderation_log_append_only on public.moderation_log;
create trigger moderation_log_append_only
  before update or delete on public.moderation_log
  for each row execute function public.block_moderation_log_mutation();

-- ---------------------------------------------------------------------------
-- 4. Revocation is always allowed — even for permanent bans
-- ---------------------------------------------------------------------------
-- A helper the server calls, so "permanent can never be irreversible" is a
-- property of the database and not only of the UI.
-- ---------------------------------------------------------------------------
create or replace function public.revoke_moderation_ban(
  p_ban_id uuid,
  p_actor_id uuid default null,
  p_actor_name text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  affected integer;
begin
  update public.moderation_bans
     set revoked_at = now(),
         revoked_by = p_actor_id,
         revoked_by_name = p_actor_name
   where id = p_ban_id
     and revoked_at is null;
  get diagnostics affected = row_count;
  return affected > 0;
end;
$$;

revoke all on function public.revoke_moderation_ban(uuid, uuid, text) from public;
grant execute on function public.revoke_moderation_ban(uuid, uuid, text) to service_role;

-- ---------------------------------------------------------------------------
-- 4b. Server-OBSERVED addresses (never client-submitted)
-- ---------------------------------------------------------------------------
-- Two tables, both written only by the server from the connection it actually
-- received:
--
--   account_ips      which address each account was last seen coming from,
--                    so "Also ban this IP address" has something real to name.
--                    ONLY the most recent address is ever offered - the owner
--                    is never handed a list of every address a player ever
--                    used, and nothing here bans an address automatically.
--   signup_attempts  a durable per-address record of registration attempts, so
--                    "one person making account after account" is still visible
--                    after a deploy wipes the process memory.
--
-- ip_key is the matching key: the address itself for IPv4, and the /64 network
-- for IPv6 (the smallest block a home is typically routed), so an IPv6 ban is
-- neither useless against rotation nor broad enough to be reckless.
-- ---------------------------------------------------------------------------
create table if not exists public.account_ips (
  account_id  uuid not null references public.accounts (id) on delete cascade,
  ip          inet not null,
  ip_key      text not null,
  first_seen  timestamptz not null default now(),
  last_seen   timestamptz not null default now(),
  times_seen  integer not null default 1,
  primary key (account_id, ip)
);

create index if not exists account_ips_recent
  on public.account_ips (account_id, last_seen desc);
create index if not exists account_ips_key
  on public.account_ips (ip_key, last_seen desc);

alter table public.account_ips enable row level security;
revoke all on public.account_ips from anon, public;
grant select, insert, update on public.account_ips to service_role;

create table if not exists public.signup_attempts (
  id        uuid primary key default gen_random_uuid(),
  ip_key    text not null,
  at        timestamptz not null default now(),
  ok        boolean not null default false,
  username  text
);

create index if not exists signup_attempts_recent
  on public.signup_attempts (ip_key, at desc);

alter table public.signup_attempts enable row level security;
revoke all on public.signup_attempts from anon, public;
grant select, insert, delete on public.signup_attempts to service_role;

-- How many sign-ups has this address managed in the last window?
-- SECURITY DEFINER with a fixed search_path, and nothing is returned except a
-- count, so it cannot be used to read anybody's history.
create or replace function public.recent_signup_count(
  p_ip_key text,
  p_minutes integer default 60
)
returns integer
language sql
security definer
set search_path = public
stable
as $$
  select count(*)::integer
    from public.signup_attempts
   where ip_key = p_ip_key
     and at > now() - make_interval(minutes => greatest(p_minutes, 1));
$$;

revoke all on function public.recent_signup_count(text, integer) from public;
grant execute on function public.recent_signup_count(text, integer) to service_role;

-- The most recent address this account was seen on, for the optional IP ban.
-- Returns NULL when nothing has been observed - in which case the owner's
-- checkbox simply has nothing to act on and says so.
create or replace function public.last_seen_ip(p_account_id uuid)
returns inet
language sql
security definer
set search_path = public
stable
as $$
  select ip
    from public.account_ips
   where account_id = p_account_id
   order by last_seen desc
   limit 1;
$$;

revoke all on function public.last_seen_ip(uuid) from public;
grant execute on function public.last_seen_ip(uuid) to service_role;

-- The most recent device this account was seen using, for the optional device
-- restriction. NULL when nothing has been registered (see the limitation the
-- dashboard states about browser device tokens).
create or replace function public.last_seen_device(p_account_id uuid)
returns text
language sql
security definer
set search_path = public
stable
as $$
  select device_id
    from public.device_accounts
   where account_id = p_account_id
   order by last_seen desc
   limit 1;
$$;

revoke all on function public.last_seen_device(uuid) from public;
grant execute on function public.last_seen_device(uuid) to service_role;

-- ---------------------------------------------------------------------------
-- 4c. Recording an observation (one round trip, written by the server only)
-- ---------------------------------------------------------------------------
-- Called by the server from a live connection, never from a request body: the
-- address it stores is the one the server actually received the connection on.
-- A failed call must never block play, so it is best-effort by design - the
-- caller logs and carries on.
-- ---------------------------------------------------------------------------
create or replace function public.record_sighting(
  p_account_id uuid,
  p_account_name text,
  p_ip inet,
  p_ip_key text,
  p_device_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_account_id is null then
    return;
  end if;

  if p_ip is not null then
    insert into public.account_ips (account_id, ip, ip_key, last_seen, times_seen)
    values (p_account_id, p_ip, p_ip_key, now(), 1)
    on conflict (account_id, ip) do update
      set last_seen = now(),
          ip_key = excluded.ip_key,
          times_seen = public.account_ips.times_seen + 1;
  end if;

  if p_device_id is not null then
    insert into public.devices (device_id, account_id, account_name, last_seen, last_ip, times_seen)
    values (p_device_id,
            p_account_id,
            p_account_name,
            now(),
            p_ip,
            1)
    on conflict (device_id) do update
      set last_seen = now(),
          times_seen = public.devices.times_seen + 1,
          -- The original account that registered the browser stays on the row;
          -- every account seen on it is recorded in device_accounts below.
          account_id = coalesce(public.devices.account_id, excluded.account_id),
          account_name = coalesce(public.devices.account_name, excluded.account_name),
          last_ip = coalesce(excluded.last_ip, public.devices.last_ip);

    insert into public.device_accounts (device_id, account_id, account_name, last_seen)
    values (p_device_id, p_account_id, p_account_name, now())
    on conflict (device_id, account_id) do update
      set last_seen = now(),
          account_name = excluded.account_name;
  end if;
end;
$$;

revoke all on function public.record_sighting(uuid, text, inet, text, text) from public;
grant execute on function public.record_sighting(uuid, text, inet, text, text) to service_role;

-- One registration attempt, recorded from the address the server saw. Used to
-- notice one person creating account after account - across restarts, which an
-- in-memory counter alone could never do.
create or replace function public.record_signup_attempt(
  p_ip_key text,
  p_username text,
  p_ok boolean default false
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.signup_attempts (ip_key, username, ok)
  values (p_ip_key, p_username, p_ok);
$$;

revoke all on function public.record_signup_attempt(text, text, boolean) from public;
grant execute on function public.record_signup_attempt(text, text, boolean) to service_role;

-- ---------------------------------------------------------------------------
-- 5. IP retention policy
-- ---------------------------------------------------------------------------
-- Addresses are the most sensitive thing moderation stores, so:
--   * they live only in moderation_bans.ip and devices.last_ip;
--   * they are never returned to any client (the server projects them away);
--   * once a restriction has been inactive for RETENTION_DAYS they are
--     overwritten with NULL, keeping the audit record but losing the address.
-- The owner can run   select public.purge_expired_moderation_ips();   from the
-- SQL Editor whenever they want the sweep done early.
-- ---------------------------------------------------------------------------
create or replace function public.purge_expired_moderation_ips(
  p_retention_days integer default 90
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  n integer;
  ip_days integer := greatest(p_retention_days, 1);
begin
  -- A ban that is no longer live keeps its audit trail but loses its address.
  update public.moderation_bans
     set ip = null
   where ip is not null
     and revoked_at is not null
     and coalesce(expires_at, revoked_at) < now()
       - make_interval(days => ip_days);
  get diagnostics n = row_count;

  update public.devices
     set last_ip = null
   where last_ip is not null
     and last_seen < now() - make_interval(days => ip_days);

  -- Observed addresses follow the same clock. An account that is still active
  -- keeps its CURRENT address (its row keeps being refreshed) and simply stops
  -- retaining older ones.
  delete from public.account_ips
   where last_seen < now() - make_interval(days => ip_days);

  -- Sign-up forensics are short-lived by design: only long enough to spot a
  -- burst, never a long-term log of where people play from.
  delete from public.signup_attempts
   where at < now() - make_interval(days => least(ip_days, 7));

  return n;
end;
$$;

revoke all on function public.purge_expired_moderation_ips(integer) from public;
grant execute on function public.purge_expired_moderation_ips(integer) to service_role;

-- ---------------------------------------------------------------------------
-- 6. Report what this migration produced
-- ---------------------------------------------------------------------------
select
  (select count(*) from public.moderation_bans)  as restrictions,
  (select count(*) from public.devices)          as devices,
  (select count(*) from public.moderation_log)   as audit_rows,
  (select count(*) from public.account_ips)      as observed_addresses,
  (select count(*) from public.signup_attempts)  as signup_attempts;
